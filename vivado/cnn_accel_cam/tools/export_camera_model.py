#!/usr/bin/env python3
"""同步相机模型的12个整数数组及输入量化标量；不读取trace，不依赖第三方库。"""
import argparse
from pathlib import Path
import re
import subprocess
import sys


def read_array(path, name, dtype, count):
    text = re.sub(r"/\*.*?\*/|//[^\n]*", "", path.read_text(), flags=re.S)
    matches = re.findall(r"\bconst\s+" + dtype + r"\s+" + re.escape(name)
                         + r"\s*\[\s*(\d*)\s*\]\s*=\s*\{([^{}]*)\}\s*;", text)
    if len(matches) != 1:
        raise ValueError(f"{path}: expected one {dtype} {name}")
    declared, body = matches[0]
    tokens = body.split(",")
    if not tokens[-1].strip():
        tokens.pop()
    if any(not re.fullmatch(r"\s*[+-]?\d+\s*", token) for token in tokens):
        raise ValueError(f"{path}: non-decimal initializer")
    values = [int(token) for token in tokens]
    bits = 8 if dtype == "int8_t" else 32
    if len(values) != count or (declared and int(declared) != count):
        raise ValueError(f"{path}: requires {count} elements")
    if any(not -(1 << (bits - 1)) <= value < (1 << (bits - 1)) for value in values):
        raise ValueError(f"{path}: {dtype} out of range")
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generated-dir", type=Path, default=Path(
        "/home/liaoyingkai/python_project/minist_train_fpga/CNN_FPGA/generated"))
    args = parser.parse_args()
    tools = Path(__file__).resolve().parent
    target = tools.parent / "vitis/cnn_accel_cam/src"
    parts = ["/* Generated by tools/export_camera_model.py; do not edit.\n"
             f" * Source: {args.generated_dir.resolve()}/headers\n"
             " * Re-export model AND input scalars: python3 tools/export_camera_model.py --generated-dir /path/to/generated\n"
             " */\n#ifndef CAMERA_MODEL_DATA_H\n#define CAMERA_MODEL_DATA_H\n"
             "#include <stdint.h>\n#define CAMERA_WEIGHT_LAYOUT_VERSION 2\n"]
    for layer, outputs, weights in (("conv1", 8, 72), ("conv2", 16, 1152), ("fc", 10, 7840)):
        weight_path = args.generated_dir / "headers" / f"{layer}_weight.h"
        if not re.search(r"^\s*#\s*define\s+" + layer.upper()
                         + r"_WEIGHT_LAYOUT_VERSION\s+2\s*$", weight_path.read_text(), re.M):
            raise ValueError(f"{weight_path}: weight layout v2 required")
        for suffix, symbol, dtype, count in (("weight", "weight", "int8_t", weights),
                ("bias", "bias", "int32_t", outputs),
                ("quant", "multiplier", "int32_t", outputs),
                ("shift", "shift", "int32_t", outputs)):
            name = f"{layer}_{symbol}"
            values = read_array(args.generated_dir / "headers" / f"{layer}_{suffix}.h", name, dtype, count)
            parts.append(f"static const {dtype} {name}[{count}] = {{\n"
                         + "\n".join("    " + ", ".join(map(str, values[i:i + 12])) + ","
                                     for i in range(0, count, 12)) + "\n};\n")
    parts.append("#endif\n")
    # 复用已有metadata校验；同一generated根同时更新输入scale，避免模型不同步。
    subprocess.run([sys.executable, str(tools / "generate_camera_model_input.py"),
                    "--metadata", str(args.generated_dir / "metadata.json"),
                    "--output", str(target / "camera_model_input.h")], check=True)
    output = target / "camera_model_data.h"
    output.write_text("\n".join(parts), encoding="utf-8")
    print(output)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"export failed: {error}", file=sys.stderr)
        sys.exit(1)
