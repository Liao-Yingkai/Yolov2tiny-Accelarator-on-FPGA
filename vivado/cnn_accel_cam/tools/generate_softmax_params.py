#!/usr/bin/env python3
"""Export the model FC output scale as one unsigned Q20 control scalar."""
import argparse
import json
import math
from pathlib import Path


def read_scale(metadata):
    data = json.loads(Path(metadata).read_text(encoding="utf-8"))
    layers = [layer for layer in data["layers"] if layer.get("name") == "fc"]
    if len(layers) != 1:
        raise ValueError("metadata requires exactly one fc layer")
    zero = layers[0].get("activation_output_zero_point",
                         data.get("activation_quantization", {}).get("zero_point"))
    if zero != 0 and zero != [0]:
        raise ValueError("FC output zero_point must be zero")
    scale = layers[0]["activation_output_scale"]
    if isinstance(scale, bool) or not isinstance(scale, (int, float)) or not math.isfinite(scale) or scale <= 0:
        raise ValueError("FC output scale must be finite and positive")
    scaled = scale * (1 << 20)
    if not math.isfinite(scaled):
        raise ValueError("FC output scale overflows Q20")
    multiplier = round(scaled)
    if not 1 <= multiplier <= 0xffffffff:
        raise ValueError("FC output Q20 scalar must fit nonzero uint32")
    return float(scale), multiplier


def generate(metadata, output):
    scale, multiplier = read_scale(metadata)
    content = ("/* Generated by generate_softmax_params.py; do not edit.\n"
               f" * Source: {Path(metadata).resolve()} (fc.activation_output_scale).\n"
               f" * Q20 scale error: {multiplier / (1 << 20) - scale!r}.\n"
               " * Floating scale is offline reference only; PS uses the integer scalar.\n"
               " */\n#ifndef MODEL_SOFTMAX_PARAMS_H\n#define MODEL_SOFTMAX_PARAMS_H\n"
               f"#define MODEL_SOFTMAX_SCALE_Q20 {multiplier}U\n"
               "#define MODEL_SOFTMAX_SCALE_FRAC_BITS 20\n"
               f"#define MODEL_FC_OUTPUT_SCALE {scale!r}\n#endif\n")
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    return scale


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metadata", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    generate(args.metadata, args.output)


if __name__ == "__main__":
    main()
