#!/usr/bin/env python3
"""Export only integer model arrays, inputs and final logits (no training)."""
import argparse
from pathlib import Path
import re
import sys


def read_array(path, name, dtype, count):
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
    pattern = (r"\bconst\s+" + dtype + r"\s+" + re.escape(name)
               + r"\s*\[\s*(\d*)\s*\]\s*=\s*\{([^{}]*)\}\s*;")
    matches = re.findall(pattern, text, flags=re.S)
    if len(matches) != 1:
        raise ValueError(f"{path}: expected one {dtype} array {name}")
    declared, body = matches[0]
    tokens = body.split(",")
    if not tokens[-1].strip():
        tokens.pop()
    if any(not re.fullmatch(r"\s*[+-]?\d+\s*", t) for t in tokens):
        raise ValueError(f"{path}: unsupported non-decimal initializer")
    values = [int(t) for t in tokens]
    if len(values) != count or (declared and int(declared) != count):
        raise ValueError(f"{path}: {name} requires {count} elements, got {len(values)}")
    bits = 8 if dtype == "int8_t" else 32
    if any(not -(1 << (bits - 1)) <= v < (1 << (bits - 1)) for v in values):
        raise ValueError(f"{path}: {name} has out-of-range {dtype} value")
    return values


def emit(dtype, name, values):
    lines = [f"static const {dtype} {name}[{len(values)}] = {{"]
    lines += ["    " + ", ".join(map(str, values[i:i + 12])) + ","
              for i in range(0, len(values), 12)]
    return "\n".join(lines + ["};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generated-dir", required=True, type=Path,
                        help="directory containing headers/ and trace/")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "src/mnist_test_data.h")
    args = parser.parse_args()
    # 拒绝旧 [K,Cout] 权重头，不能仅凭相同元素数量误用新 DDR ABI。
    for layer in ("conv1", "conv2", "fc"):
        path = args.generated_dir / "headers" / f"{layer}_weight.h"
        macro = f"{layer.upper()}_WEIGHT_LAYOUT_VERSION"
        if not re.search(r"^\s*#\s*define\s+" + macro + r"\s+2\s*$",
                         path.read_text(encoding="utf-8"), flags=re.M):
            raise ValueError(f"{path}: requires {macro}=2")
    parts = ["/* Generated by tools/export_test_data.py; do not edit.\n"
             " * Source: CNN_FPGA/generated/{headers,trace}; integer arrays only.\n"
             " * Re-export: python3 tools/export_test_data.py --generated-dir /path/to/CNN_FPGA/generated\n"
             " */\n#ifndef MNIST_TEST_DATA_H\n#define MNIST_TEST_DATA_H\n#include <stdint.h>\n"
             "#define MNIST_WEIGHT_LAYOUT_VERSION 2\n"
             "enum { MNIST_TEST_COUNT = 3, MNIST_INPUT_COUNT = 784, MNIST_LOGIT_COUNT = 10 };\n"]
    for layer, outputs, weights in (("conv1", 8, 72), ("conv2", 16, 1152), ("fc", 10, 7840)):
        for suffix, symbol, dtype, count in (("weight", "weight", "int8_t", weights),
                                             ("bias", "bias", "int32_t", outputs),
                                             ("quant", "multiplier", "int32_t", outputs),
                                             ("shift", "shift", "int32_t", outputs)):
            name = f"{layer}_{symbol}"
            parts.append(emit(dtype, name, read_array(args.generated_dir / "headers" / f"{layer}_{suffix}.h", name, dtype, count)))
    for index in range(3):
        source = args.generated_dir / "trace" / f"trace_data_{index:04d}.h"
        for source_name, dest, count in (("trace_input_int8_hwc", "input", 784),
                                         ("trace_fc_requant_int8", "logits", 10)):
            parts.append(emit("int8_t", f"mnist_{dest}_{index}", read_array(source, source_name, "int8_t", count)))
    for kind, table in (("input", "mnist_inputs"), ("logits", "mnist_expected_logits")):
        parts.append(f"static const int8_t * const {table}[MNIST_TEST_COUNT] = {{\n"
                     + ", ".join(f"mnist_{kind}_{i}" for i in range(3)) + "\n};\n")
    parts.append("#endif\n")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(parts), encoding="utf-8")
    print(f"Exported model and 3 tests to {args.output}")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        print(f"export failed: {error}", file=sys.stderr)
        sys.exit(1)
